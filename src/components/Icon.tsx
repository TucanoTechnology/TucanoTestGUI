import type { ReactNode, SVGProps } from "react";

/**
 * The application's icon set (#180): one small hand-rolled family in place of
 * the emoji glyphs. Every icon is 24×24 geometry stroked at one weight in
 * `currentColor`, so it takes the colour of whatever state the CSS puts it in
 * — the nav rail's active switch from secondary to primary now repaints the
 * icon with the label it belongs to. Icons are decorative by default: each
 * call site pairs them with visible text or an `aria-label`, and a `title` is
 * the opt-in for the rare icon that carries meaning alone (it then promotes
 * the SVG to an image with an accessible name).
 */
interface IconProps extends Omit<SVGProps<SVGSVGElement>, "title"> {
  title?: string;
}

function Svg({ title, children, ...rest }: IconProps & { children: ReactNode }) {
  const labelled = title !== undefined && title.length > 0;
  return (
    <svg
      viewBox="0 0 24 24"
      width="1em"
      height="1em"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={labelled ? "img" : undefined}
      aria-hidden={labelled ? undefined : true}
      focusable={false}
      {...rest}
    >
      {labelled ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}

